// 초기 / 배변 두 시점의 배당 컬럼. E_ 접두사가 배변(움직인 뒤)이다.
const COLS = {
  init: { fw: 'FW', fd: 'FD', fl: 'FL', kw: 'KW', kd: 'KD', kl: 'KL' },
  final: { fw: 'EFW', fd: 'EFD', fl: 'EFL', kw: 'EKW', kd: 'EKD', kl: 'EKL' },
}

function num(v) {
  if (v === null || v === undefined || v === '') return null
  const n = Number(v)
  return Number.isFinite(n) && n > 0 ? n : null
}

function bin(v, cuts) {
  for (let i = 0; i < cuts.length; i += 1) if (v < cuts[i]) return i
  return cuts.length
}

// 한 시장(국내 또는 해외)에서 정배배당·무배당·정배가 홈인지를 뽑는다.
function readMarket(row, w, d, l) {
  const a = num(row[w])
  const dd = num(row[d])
  const b = num(row[l])
  if (a === null || dd === null || b === null || a === b) return null
  return { fav: Math.min(a, b), draw: dd, homeFav: a < b }
}

/**
 * 그 시점에 등록된 배당 전부로 예상점수를 만든다 (CLAUDE.md 4-1).
 * 국내배당이 아직 없으면 해외만으로, 등록되면 둘을 평균해 다시 계산한다.
 *
 * @param {object} row   경기 한 줄
 * @param {string} pick  시스템 판정이 정한 픽(정무/정역/플핸무/플핸승)
 * @param {boolean} final false=초기 / true=배변
 * @returns {{home:number, away:number, rate:number, n:number, markets:number}|null}
 */
export function expectedScore(row, pick, final) {
  const t = TABLE[pick]
  if (!t) return null
  const c = final ? COLS.final : COLS.init
  const forr = readMarket(row, c.fw, c.fd, c.fl)
  const dom = readMarket(row, c.kw, c.kd, c.kl)
  const mkts = [forr, dom].filter(Boolean)
  if (!mkts.length) return null

  // 정배가 어느 쪽인지는 해외배당으로 정한다 — 시스템 판정과 같은 기준이어야
  // "정역인데 스코어는 무승부" 같은 모순이 안 생긴다(국내·해외가 갈리는 경기 4.25%).
  const homeFav = (forr || dom).homeFav
  const fav = mkts.reduce((s, m) => s + m.fav, 0) / mkts.length
  const draw = mkts.reduce((s, m) => s + m.draw, 0) / mkts.length

  const cell = t[`${bin(fav, FAV_CUTS)}${bin(draw, DRAW_CUTS)}`]
  if (!cell) return null
  const [fg, ug, rate, n] = cell
  return {
    home: homeFav ? fg : ug,
    away: homeFav ? ug : fg,
    rate,
    n,
    markets: mkts.length,
  }
}
